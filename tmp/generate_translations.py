# We'll use custom formatting to match Android XML specs with double quotes or proper escapes
def write_android_xml(path, strings_dict):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n')
        f.write('<resources>\n')
        for key, val in strings_dict.items():
            # Clean up escape sequences for Android strings (e.g. escaping quotes and backslashes)
            clean_val = val.replace('"', '\\"').replace("'", "\\'")
            f.write(f'    <string name="{key}">{clean_val}</string>\n')
        f.write('</resources>\n')

